import { findHintMove } from './findHintMove';

/**
 * Тесты пишут сетку колонками, как её хранит рантайм: `grid[col][row]`,
 * где `col` - столбец, `row` - строка сверху вниз.
 */
const columns = (...cols: (string | null)[][]): (string | null)[][] => cols;

describe('findHintMove', () => {
  it('находит свап с соседом снизу, собирающий вертикальную тройку', () => {
    // Свап (1,1)<->(2,1): первый столбец становится xxx.
    const grid = columns(['b', 'a', 'b'], ['x', 'd', 'x'], ['b', 'x', 'a']);

    expect(findHintMove(grid)).toEqual([
      { col: 1, row: 1 },
      { col: 2, row: 1 },
    ]);
  });

  it('находит свап с соседом справа, собирающий горизонтальную тройку', () => {
    // Свап (1,1)<->(1,2): средняя строка становится xxx.
    const grid = columns(['b', 'x', 'b'], ['a', 'd', 'x'], ['b', 'x', 'a']);

    expect(findHintMove(grid)).toEqual([
      { col: 1, row: 1 },
      { col: 1, row: 2 },
    ]);
  });

  it('выбирает ход ближе к центру поля, а не первый по обходу сверху слева', () => {
    const grid = columns(
      ['a', 'e', 'i', 'k', 'o'],
      ['b', 'a', 'x', 'l', 'p'],
      ['a', 'x', 'y', 'x', 'q'],
      ['c', 'g', 'x', 'm', 'r'],
      ['d', 'h', 'j', 'n', 's']
    );

    expect(findHintMove(grid)).toEqual([
      { col: 1, row: 2 },
      { col: 2, row: 2 },
    ]);
  });

  it('возвращает null в сетке без ходов', () => {
    // Горизонтали без повторов, колонки с периодом 2: ни один свап не
    // собирает линию из трёх.
    const grid = columns(
      ['a', 'c', 'a', 'c'],
      ['b', 'd', 'b', 'd'],
      ['c', 'a', 'c', 'a'],
      ['d', 'b', 'd', 'b']
    );

    expect(findHintMove(grid)).toBeNull();
  });

  it('клетки без фишек не участвуют в линии', () => {
    // Тот же ход, что в первом тесте, но клетка линии (1,0) пуста:
    // собирающаяся тройка разваливается, хода нет.
    const grid = columns(['b', 'a', 'b'], [null, 'd', 'x'], ['b', 'x', 'a']);

    expect(findHintMove(grid)).toBeNull();
  });

  it('находит свап, замыкающий квадрат 2×2, когда он ближе к центру', () => {
    // Свап (2,1)<->(2,2) замыкает квадрат a в колонках 1-2, строках 0-1.
    // Ход-линия рядом есть всегда (у квадрата и линии общие фишки), но он
    // дальше от центра; клетка (1,2) - блокер, иначе линия нашлась бы на
    // том же расстоянии.
    const grid = columns(
      ['p', 'q', 'r', 's', 't'],
      ['a', 'a', null, 'v', 'w'],
      ['a', 'x', 'a', 'y', 'z'],
      ['b', 'c', 'd', 'e', 'f'],
      ['g', 'h', 'i', 'j', 'k']
    );

    expect(findHintMove(grid)).toEqual([
      { col: 2, row: 1 },
      { col: 2, row: 2 },
    ]);
  });
});

/**
 * Правила отложенного ввода: доска была занята чужим каскадом, тап или свайп
 * игрока лёг в буфер (`modules/PendingBoardInput`), и на освобождении
 * рантайма надо решить, доигрывать его или отбросить.
 *
 * Живёт отдельным чистым правилом, потому что буферов уже два, условие у них
 * общее, а копия этого условия в каждом флаше рано или поздно разойдётся:
 * забытый гейт по `isGameEnded` означает каскад, который пишет прогресс целей
 * в стор уже после принятого исхода. Про рантайм и сторы правило не знает,
 * состояние собирает вызывающий - поэтому проверяется тестами.
 */

/** Клетка доски: `col` - колонка (`entity.x`), `row` - строка (`entity.y`). */
export interface IPendingCell {
  col: number;
  row: number;
}

export interface IPendingInputGate {
  /**
   * Сущность, с которой был сделан ввод, всё ещё стоит в своей клетке грида.
   * За время ожидания её мог снести матч или чужой лазер.
   */
  isEntityOnBoard: boolean;
  /**
   * Партия завершена: исход принят, доска уходит в финальную сцену. Доигрывать
   * отложенный ввод поверх этого нельзя - каскад продолжил бы писать прогресс
   * целей уже после `finish`.
   */
  isGameEnded: boolean;
  /**
   * Рантайм упал. `setProcessing(false)` зовётся и из аварийной разблокировки
   * (`releaseBoard` в `runGuarded.onFailure`), то есть флаш случается ровно на
   * сломанном сценарии - запускать на нём новый каскад незачем.
   */
  hasRuntimeFailure: boolean;
}

/** Можно ли доигрывать отложенный ввод. */
export const canReplayPendingInput = (gate: IPendingInputGate): boolean =>
  gate.isEntityOnBoard && !gate.isGameEnded && !gate.hasRuntimeFailure;

/**
 * Свайп - отдельное правило поверх общего: он переигрывается только с той же
 * клетки, с которой был сделан.
 *
 * Буферизуется свайп ровно потому, что идёт каскад, а каскад - это гравитация:
 * фишка почти наверняка уедет вниз. Переиграть жест «от её новой клетки»
 * значит выполнить ход в месте, которого игрок не выбирал, и списать за него
 * ход. Уехала фишка - свайп отбрасываем; успел закончиться короткий каскад,
 * не задевший её колонку, - доигрываем, ради чего буфер и заведён.
 */
export const canReplayPendingSwap = (
  gate: IPendingInputGate,
  origin: IPendingCell,
  current: IPendingCell
): boolean =>
  canReplayPendingInput(gate) && origin.col === current.col && origin.row === current.row;

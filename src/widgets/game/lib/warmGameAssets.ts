import { preloadImages } from '@/shared/lib/assets';

/**
 * Прогрев уже запущен (или закончен) в этом запуске приложения.
 *
 * Набор текстур доски статичен и от уровня не зависит, поэтому греть его
 * повторно на каждую партию незачем: второй прогрев - это ещё 55 объектов
 * `Image` и столько же таймеров ожидания, которые ничего не добавляют к уже
 * заполненному HTTP-кэшу.
 *
 * Промис не отменяется по уходу с экрана игры намеренно. `preloadImages` без
 * `signal` не реджектится вовсе (ошибка и таймаут конкретного файла - это
 * `false`, см. `preloadImage`), а прерывание выбросило бы ровно тот кэш, ради
 * которого всё и затевалось: следующая партия качала бы текстуры заново.
 * Хвост ожидания ограничен таймаутом самого `preloadImage`.
 */
let warmPromise: Promise<void> | null = null;

interface IWarmGameAssetsOptions {
  /**
   * Ход прогрева по файлам - для бара лоадера. Получает его только вызов,
   * который прогрев запустил: повторный вызов возвращает уже идущий промис.
   */
  onProgress?: (done: number, total: number) => void;
}

/**
 * Браузерный прогрев текстур доски до того, как рантайм партии поднимется.
 *
 * Набор текстур от уровня не зависит, поэтому он прогревается параллельно со
 * стартом: к моменту, когда загрузчик рантайма запросит файлы, они уже в
 * HTTP-кэше браузера.
 *
 * Чтобы прогрев и загрузчик рантайма попали в один кэш, оба запрашивают
 * картинки с `crossOrigin: 'anonymous'`: запись кэша от no-cors `<img>`
 * CORS-запрос переиспользовать не может (`docs/PLAN.md`, таблица соответствия).
 *
 * Ошибка конкретного файла не роняет сценарий (см. `preloadImage`): загрузчик
 * рантайма перезапросит файл сам и при неудаче уйдёт в `failRuntime('assets')`.
 */
export const warmGameAssets = ({ onProgress }: IWarmGameAssetsOptions = {}): Promise<void> => {
  // Список URL - из скина, и скин (описание элементов, процедурное рисование)
  // приезжает отдельным чанком: этот модуль - в баррели виджета без движка,
  // который лежит в стартовом графе хоста. Чанк общий с рантаймом партии, так
  // что запрос не лишний - к старту рантайма он уже загружен.
  warmPromise ??= import('../configs/assetsConfig')
    .then(({ getGameAssetImageUrls }) =>
      preloadImages(getGameAssetImageUrls(), {
        // То же значение, что у загрузчика рантайма: запись кэша от no-cors
        // `<img>` он переиспользовать не сможет.
        crossOrigin: 'anonymous',
        onProgress,
      })
    )
    // Прогрев - не обязательный шаг: не загрузился даже чанк - загрузчик
    // рантайма запросит файлы сам и сам же уйдёт в `failRuntime('assets')`.
    .then(
      () => undefined,
      () => undefined
    );

  return warmPromise;
};

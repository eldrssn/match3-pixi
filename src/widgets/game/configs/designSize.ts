/**
 * Дизайн-сетка игрового мира. Всё, что рисуют модули сцены, задано в этих
 * координатах, а под реальный канвас мир вписывается общим множителем
 * `min(width / DESIGN_WIDTH, height / DESIGN_HEIGHT)` (см. `renderScale.ts`).
 *
 * Отдельный модуль, а не два экспорта из `GAME_CONFIG`, ровно по одной
 * причине: `renderScale` считает по этим числам разрешение, с которым печётся
 * текст, а `GAME_CONFIG` берёт это разрешение у `renderScale`. Пока константы
 * лежали в `GAME_CONFIG`, такая связь была бы циклом импортов, и порядок
 * вычисления модулей решал бы, не окажется ли одна из сторон `undefined`.
 * `GAME_CONFIG` их реэкспортирует, поэтому потребителям менять импорт не надо.
 */
export const DESIGN_WIDTH = 360;
export const DESIGN_HEIGHT = 744;

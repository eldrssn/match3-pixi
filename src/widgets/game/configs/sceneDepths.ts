/**
 * Глубины в корне сцены партии - то, что обязано лечь поверх слоёв
 * (`LayerManager`: контейнеры с глубиной 0 в порядке создания).
 *
 * Инвариант у чисел цепочкой, поэтому они живут одним местом: независимые
 * литералы в разных модулях разъехались бы молча - панель целей оказалась бы
 * под собственным затемнением, а летящая цель под панелью.
 */

/** Затемнение интро цели (`GoalIntro`): цель читается, поле за ней нет. */
export const GOAL_INTRO_OVERLAY_DEPTH = 1000;

/** Слой панели целей (`GameGoalsPannel`) - над затемнением интро. */
export const GOAL_PANEL_LAYER_DEPTH = GOAL_INTRO_OVERLAY_DEPTH + 1;

/** Копия собранной цели в полёте (`lib/goalFlight`) - над всей шапкой, включая панель целей. */
export const GOAL_FLIGHT_DEPTH = GOAL_PANEL_LAYER_DEPTH + 1;

/**
 * Вспышка кадра (`IBoardFx.flashBoard`) - поверх всего, как вспышка камеры
 * эталона: та рисуется после сцены целиком, включая шапку и полёт цели.
 */
export const CAMERA_FLASH_DEPTH = GOAL_FLIGHT_DEPTH + 1;

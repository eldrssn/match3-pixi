import { resolveSceneLayout } from '../lib/sceneLayout';
import { getRenderQuality, LOW_QUALITY_DPR_CAP } from './renderQuality';
import { getSceneInsets } from './sceneInsets';

/**
 * Разрешение отрисовки игрового канваса.
 *
 * Канвас рисует в физических пикселях устройства, а не в CSS-пикселях:
 * внутренний размер равен CSS-размеру доски, умноженному на DPR
 * (`resolution` рендерера Pixi), а `autoDensity` возвращает канвасу исходный
 * CSS-размер - сцена при этом живёт в CSS px. Без этого канвас рендерился в
 * CSS-разрешении и растягивался на втрое более плотный экран - отсюда мыло и
 * «лесенки» на фишках. Запас в ассетах для этого уже есть: игровой арт нарисован
 * в 4x к дизайн-сетке 360x744 и рисуется через `setScale(0.25)`.
 */

/**
 * Кап равен максимальному DPR, который встречается на телефонах, то есть
 * фактически не срезает ничего.
 *
 * Кап ниже (скажем, 2.5) экономил бы fillrate, но ценой единственного, ради
 * чего весь этот модуль и написан. На DPR-3 устройстве (440 CSS px доски)
 * бэкбуфер получался бы 1100 px против 1320 физических пикселей экрана, и
 * композитор растягивал бы **весь** кадр на 1.2x. Фишка при этом рисовалась бы
 * в 128 px канваса и растягивалась до 154, хотя её исходник (160 px) на эти 154
 * хватает с запасом: пятая часть линейного разрешения, уже оплаченного
 * ассетами, выбрасывалась бы впустую.
 *
 * Цена подъёма - площадь бэкбуфера: 1320x2868 против 1100x2390, то есть
 * fillrate x1.44. Это единственное, что здесь надо мерить при регрессе FPS.
 */
export const RENDER_DPR_CAP = 3;

/**
 * DPR отрисовки: экранный, но не выше капа. Низкое качество (перф-гейт,
 * `configs/renderQuality`) опускает кап - бэкбуфер становится меньше.
 */
export const getRenderDpr = (): number => {
  if (typeof window === 'undefined') {
    return 1;
  }

  const cap = getRenderQuality() === 'low' ? LOW_QUALITY_DPR_CAP : RENDER_DPR_CAP;

  return Math.min(Math.max(window.devicePixelRatio || 1, 1), cap);
};

/**
 * Внутренний размер канваса последней партии, в физических пикселях.
 *
 * Публикует его ядро рантайма (`GameRuntimeCore.resize`) - CSS-размер доски,
 * умноженный на DPR отрисовки, то есть размер бэкбуфера. По нему
 * `getTextResolution()` считает разрешение печати текста.
 *
 * `null` до первого замера доски: до него единственное, что известно про
 * плотность экрана, - это DPR.
 */
let renderCanvasSize: { width: number; height: number } | null = null;

export const setRenderCanvasSize = (width: number, height: number): void => {
  if (width <= 0 || height <= 0) {
    return;
  }

  renderCanvasSize = { width, height };
};

/**
 * Забыть размер канваса.
 *
 * Зовёт его владелец рантайма (`bootGameRuntime`) - на старте партии, у
 * которой размер ещё не измерен, и на уничтожении игры. Без сброса значение
 * пережило бы сессию, и следующая партия, стартовавшая до первого замера
 * доски, пекла бы текст по размеру канваса **прошлой** - это хуже честного
 * фолбэка по DPR, потому что ошибка молчаливая и зависит от того, во что
 * играли до этого.
 */
export const resetRenderCanvasSize = (): void => {
  renderCanvasSize = null;
};

/**
 * Множитель, которым мир вписывается в бэкбуфер, в физических пикселях - то
 * же `resolveSceneLayout`, что раскладывает сцену (`GameRuntimeCore`), только
 * в пикселях бэкбуфера, а не в CSS px: отступы переводятся по DPR.
 *
 * Фолбэк на DPR - не эквивалент, а нижняя граница: доска не уже дизайн-сетки,
 * поэтому `worldScale >= dpr` всегда. Занизить разрешение текста до замера
 * доски безопаснее, чем завысить.
 */
export const getWorldScale = (): number => {
  if (!renderCanvasSize) {
    return getRenderDpr();
  }

  return resolveSceneLayout(renderCanvasSize, getSceneInsets(), getRenderDpr()).scale;
};

/**
 * Текст на канвасе растеризуется в текстуру один раз, по своему
 * `resolution`, и реактивно его не меняет.
 *
 * Считается от `worldScale`, а не от DPR, потому что растягивает текст именно
 * он: контейнеры сцены масштабируются на `worldScale`, и на 440 CSS px доски
 * при DPR 3 это 3.67 против `ceil(DPR) = 3` - текст остался бы единственным
 * мыльным слоем на резком фоне, растянутым на 22%.
 *
 * Верхнего предела нет намеренно: `worldScale` ограничен размером канваса, а
 * тот - шириной шелла, так что выше 4-5 значение не поднимется, и это несколько
 * коротких надписей на партию.
 */
export const getTextResolution = (): number => Math.ceil(getWorldScale());
